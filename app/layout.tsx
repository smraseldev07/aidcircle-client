import type { Metadata } from "next";
import Script from "next/script";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { Navbar } from "@/components/navbar";
import { Footer } from "@/components/footer";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Applies the persisted theme (or the system preference) before React
// hydrates, so a dark-mode user doesn't see a white flash. ThemeToggle
// in components/theme-toggle.tsx flips the same class + storage key.
const themeScript = `
(function () {
  try {
    var stored = localStorage.getItem("aidcircle:theme");
    var dark = stored
      ? stored === "dark"
      : window.matchMedia("(prefers-color-scheme: dark)").matches;
    document.documentElement.classList.toggle("dark", dark);
    document.documentElement.style.colorScheme = dark ? "dark" : "light";
  } catch (e) {}
})();
`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/* Runs before hydration so a dark-mode user never sees a white
            flash. ThemeToggle in components/theme-toggle.tsx flips the
            same class + storage key. */}
        <Script id="theme-init" strategy="beforeInteractive">
          {themeScript}
        </Script>
         <Navbar />
        {children}
         <Footer />
        </body>
    </html>
  );
}
